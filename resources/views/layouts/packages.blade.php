// Show individual short-term option details
function showShortTermDetails(option) {
    const modal = document.getElementById('packageModal');
    const content = document.getElementById('modalPackageContent');
    
    if (shortTermDetails[option]) {
        content.innerHTML = shortTermDetails[option];
        modal.classList.add('active');
        document.body.style.overflow = 'hidden';
    }
}
function hideShortTermDetails() {
    const modal = document.getElementById('shortTermModal');
    modal.classList.remove('active');
    document.body.style.overflow = 'auto';
}

// Close modals when clicking outside content
document.addEventListener('click', function(event) {
    const packageModal = document.getElementById('packageModal');
    const shortTermModal = document.getElementById('shortTermModal');
    
    if (event.target === packageModal) {
        hidePackageDetails();
    }
    
    if (event.target === shortTermModal) {
        hideShortTermDetails();
    }
});

// Close modals with Escape key
document.addEventListener('keydown', function(event) {
    if (event.key === 'Escape') {
        hidePackageDetails();
        hideShortTermDetails();
    }
});
